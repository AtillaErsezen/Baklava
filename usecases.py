def _w(alt: str) -> str:
    """Regex: one of the alternatives as a whole snake_case word run."""
    return rf"(^|_)({alt})(_|$)"


def _x(alt: str) -> str:
    """Regex: the whole column name is one of the alternatives."""
    return rf"^({alt})$"


