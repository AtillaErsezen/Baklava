_ENDINGS = (("ation", 3), ("ion", 4), ("ing", 4), ("ed", 4), ("ly", 3), ("e", 3))


def _stem(t: str) -> str:
    """Tiny deterministic stemmer: irregular map, plural strip, one derivational ending."""
    t = _IRREGULAR.get(t, t)
    if t.endswith("ies") and len(t) > 4:
        t = t[:-3] + "y"
    elif t.endswith("s") and len(t) > 3 and not t.endswith(("ss", "us", "is")):
        t = t[:-1]
    t = _IRREGULAR.get(t, t)
    for end, keep in _ENDINGS:
        if t.endswith(end) and len(t) - len(end) >= keep:
            return t[:-len(end)]
    return t


def _tokens(text: str) -> list[str]:
    out = []
    for raw in re.findall(r"[a-z0-9]+", text.lower()):
        if len(raw) < 2 or raw in _STOP:
            continue
        t = _stem(raw)
        if t not in _STOP:
            out.append(t)
    return out


_VEC = TfidfVectorizer(tokenizer=_tokens, token_pattern=None, lowercase=True, ngram_range=(1, 2), sublinear_tf=True)
_PHRASES = [(i, q) for i, u in enumerate(USE_CASES) for q in u["questions"]]
_P = _VEC.fit_transform([q for _, q in _PHRASES])
_DOCS = _VEC.transform([u["name"] + " " + " ".join(u["questions"]) for u in USE_CASES])

# ---- column matching
_NOT_TARGET = re.compile(r"(^|_)(lag|lead|rolling|roll|ewm|ewma|diff|shift|ma|mean|std|sum|min|max)_?\d"
                         r"|(^|_)(lag|rolling|ewm|shift)(_|$)|(^|_)(id|uuid|date|dt|at|timestamp)$")
_rx = lru_cache(maxsize=None)(re.compile)


def _snake(col: str) -> str:
    """SalePrice -> sale_price, 'No-show' -> no_show."""
    s = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", str(col))
    return re.sub(r"[^a-z0-9]+", "_", s.lower()).strip("_")


def _hits(patterns: list[str], names: list[str]) -> list[bool]:
    return [any(_rx(p).search(n) for p in patterns) for n in names]


def leakage_suspects(uc: dict, columns: list[str]) -> list[str]:
    """Columns whose names match the use case's leakage patterns (information from after the event)."""
    return [c for c, hit in zip(columns, _hits(uc["leakage_patterns"], [_snake(c) for c in columns])) if hit]


def suggest_target(uc: dict, columns: list[str]) -> str | None:
    """First column matching target_hint in pattern order, skipping leaks, ids, dates and lag features."""
    leaks = set(leakage_suspects(uc, columns))
    names = [(c, _snake(c)) for c in columns if c not in leaks]
    for p in uc["target_hint"]:
        for c, n in names:
            if not _NOT_TARGET.search(n) and _rx(p).search(n):
                return c
    return None


def _column_score(uc: dict, columns: list[str], names: list[str]) -> tuple[float, list[str]]:
    target = suggest_target(uc, columns)
    found = [c for c, hit in zip(columns, _hits(uc["needed_columns"], names)) if hit]
    covered = sum(any(_rx(p).search(n) for n in names) for p in uc["needed_columns"])
    reasons = ([f"target candidate column: {target}"] if target else []) + (
        [f"expected columns present: {', '.join(found[:6])}"] if found else [])
    return 0.6 * (target is not None) + 0.4 * covered / len(uc["needed_columns"]), reasons


def match(purpose: str, columns: list[str], task_hint: str | None = None, top_k: int = 3) -> list[dict]:
    """Rank use cases for a goal and dataset columns; each result is the entry plus score in [0, 1] and reasons.

    text = cosine blend scaled by sqrt(share of goal words known to the catalog vocabulary);
    score = (1 - COL_WEIGHT) * text + COL_WEIGHT * columns, halved when task_hint disagrees.
    task_hint: classification | regression | binary | multiclass | forecast | None.
    """
    if task_hint is not None and task_hint not in _HINT_KIND:
        raise ValueError(f"task_hint must be one of {sorted(_HINT_KIND)} or None, got {task_hint!r}")
    columns = [str(c) for c in columns or []]
    names = [_snake(c) for c in columns]
    toks = _tokens(purpose or "")
    coverage = sum(t in _VEC.vocabulary_ for t in toks) / len(toks) if toks else 0.0
    q = _VEC.transform([purpose or ""])
    phrase_sims = (_P @ q.T).toarray().ravel()
    doc_sims = (_DOCS @ q.T).toarray().ravel()
    best = np.zeros(len(USE_CASES))
    best_q = [""] * len(USE_CASES)
    for (i, text), s in zip(_PHRASES, phrase_sims):
        if s > best[i]:
            best[i], best_q[i] = s, text
    out = []
    for i, uc in enumerate(USE_CASES):
        # unknown words vanish from the tf-idf vector; scale down so one known word cannot look like a match
        text = (BEST_PHRASE * best[i] + (1 - BEST_PHRASE) * doc_sims[i]) * coverage ** 0.5
        col, reasons = _column_score(uc, columns, names)
        score = (1 - COL_WEIGHT) * text + COL_WEIGHT * col
        if best_q[i]:
            reasons = [f'goal resembles "{best_q[i]}" (similarity {best[i]:.2f})'] + reasons
        if task_hint and _HINT_KIND[task_hint] != TASK_KIND[uc["task"]]:
            score *= TASK_MISMATCH
            reasons.append(f"task hint {task_hint} does not fit {uc['task']}")
        out.append({**uc, "score": round(float(min(max(score, 0.0), 1.0)), 4),
                    "reasons": reasons or ["no overlap with the goal or the columns"]})
    return sorted(out, key=lambda m: (-m["score"], m["id"]))[:max(top_k, 0)]
